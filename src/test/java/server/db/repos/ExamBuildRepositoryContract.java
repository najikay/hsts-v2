    @Test
    @DisplayName("every version is listed, drafts included, newest first")
    void versionListIncludesDraftsNewestFirst() {
        long examId = inTx(session -> repository.insertExam(session, COURSE_ALGEBRA, danaId));
        long v1 = inTx(session -> repository.insertDraftVersion(session, examId, 1, "v1", 60, null, null, WHEN));
        long v2 = inTx(session -> repository.insertDraftVersion(session, examId, 2, "v2", 60, null, null, WHEN));
        approve(v1);

        List<AuthoredVersionRow> rows = inTx(session -> repository.findAuthoredVersions(session, danaId));

        assertThat(rows).extracting(AuthoredVersionRow::versionNo).containsExactly(2, 1);
        assertThat(rows).extracting(AuthoredVersionRow::status)
                .containsExactly(ExamVersionStatus.DRAFT, ExamVersionStatus.APPROVED);
        assertThat(rows).extracting(AuthoredVersionRow::examId).containsOnly(examId);
        assertThat(rows).extracting(AuthoredVersionRow::examVersionId).containsExactly(v2, v1);

        // The optimistic token, and it has to be THIS version's. approve() bumped v1's @Version
        // to 1 while v2 was never written again, so the two rows carry different tokens and a
        // constructor expression that picked up the wrong column - the duration, the exam's own
        // lock, or a literal - can no longer pass. Every other assertion in this class read a row
        // whose lockVersion was 0, which is the default, so a swap survived the whole suite.
        assertThat(rows).extracting(AuthoredVersionRow::lockVersion).containsExactly(0, 1);
        assertThat(rows).extracting(AuthoredVersionRow::durationMinutes).containsOnly(60);
        assertThat(rows).extracting(AuthoredVersionRow::createdAt).containsOnly(WHEN);
    }


    @Test
    @DisplayName("the same question through two of its versions is refused by the schema (T-3.9)")
    void oneQuestionCannotAppearTwiceThroughTwoVersions() {
        // PRD §6's "duplicate question in exam -> prevented", and the constraint behind it. The
        // service refuses this first with a sentence naming the question, because the constraint's
        // own message is not something a teacher can act on. This asserts the backstop is really
        // there, so a service check that gets removed does not silently let a duplicate onto a
        // paper. It lives in the contract because H2 reproduces the unique too.
        long versionId = draftVersion();
        long questionId = questionWithVersions("שאלה כפולה", 2);

        assertThatThrownBy(() -> runInTx(session -> repository.replaceComposition(session, versionId,
                List.of(new ExamBuildRepository.Pin(versionIdOf(session, questionId, 1), questionId, 50, 1),
                        new ExamBuildRepository.Pin(versionIdOf(session, questionId, 2), questionId, 50, 2)))))
                // Named, not merely non-null. isNotNull() passes for any throwable, including an
                // NPE from a fixture helper returning a null version id - and the assertion below
                // would agree with it, because nothing was written either way. Both engines report
                // the constraint name, though they decorate it differently (H2 appends _INDEX_n,
                // MySQL prefixes the table), so this contains rather than equals.
                .isInstanceOf(ConstraintViolationException.class)
                .hasMessageContaining("uq_exam_version_questions_question");

        List<PinnedQuestion> afterRollback = inTx(session -> repository.findComposition(session, versionId));
        assertThat(afterRollback)
                .as("the whole transaction rolled back, so no half-written paper survives")
                .isEmpty();
    }


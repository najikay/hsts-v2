    /** A question in Algebra with {@code versions} versions, numbered from 1. */
    private long questionWithVersions(String text, int versions) {
        long questionId = persistQuestion();
        for (int versionNo = 1; versionNo <= versions; versionNo++) {
            int number = versionNo;
            runInTx(session -> session.persist(new QuestionVersion(questionId, number, text,
                    "1", "2", "3", "4", (byte) 1, "פונקציות", Difficulty.EASY,
                    null, danaId, WHEN)));
        }
        return questionId;
    }

    private long questionWithImage() {
        long questionId = persistQuestion();
        runInTx(session -> session.persist(new QuestionVersion(questionId, 1, "עם תמונה",
                "1", "2", "3", "4", (byte) 1, "פונקציות", Difficulty.EASY,
                new byte[] {1, 2, 3}, danaId, WHEN)));
        return questionId;
    }

    private long persistQuestion() {
        return inTx(session -> {
            short serial = (short) (countQuestions(session) + 1);
            Question question = new Question(COURSE_ALGEBRA, serial,
                    COURSE_ALGEBRA + String.format("%03d", serial));
            session.persist(question);
            session.flush();
            return question.getId();
        });
    }

    private long countQuestions(org.hibernate.Session session) {
        return session.createQuery("select count(q) from Question q", Long.class).uniqueResult();
    }

    private void softDelete(long questionId) {
        runInTx(session -> session.get(Question.class, questionId).setDeletedAt(WHEN));
    }

    private void approve(long examVersionId) {
        runInTx(session -> session.get(ExamVersion.class, examVersionId).approve());
    }

    private void reject(long examVersionId, String reason) {
        runInTx(session -> session.get(ExamVersion.class, examVersionId).reject(reason));
    }

    private String displayIdOf(long examId) {
        return inTx(session -> session.get(Exam.class, examId).getDisplayId());
    }

    private long versionIdOf(org.hibernate.Session session, long questionId, int versionNo) {
        return session.createQuery("""
                        select qv.id from QuestionVersion qv
                        where qv.questionId = :questionId and qv.versionNo = :versionNo
                        """, Long.class)
                .setParameter("questionId", questionId)
                .setParameter("versionNo", versionNo)
                .uniqueResult();
    }

    private long latestVersionIdOf(org.hibernate.Session session, long questionId) {
        return session.createQuery("""
                        select qv.id from QuestionVersion qv
                        where qv.questionId = :questionId
                          and qv.versionNo = (select max(later.versionNo) from QuestionVersion later
                                              where later.questionId = :questionId)
                        """, Long.class)
                .setParameter("questionId", questionId)
                .uniqueResult();
    }

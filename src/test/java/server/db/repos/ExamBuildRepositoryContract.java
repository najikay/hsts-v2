    @Test
    @DisplayName("re-saving the same questions at new positions replaces rather than collides")
    void replacingAtNewOrdinalsDoesNotCollide() {
        // Re-pinning the same questions at new ordinals is the case that would collide if the
        // delete were queued rather than executed. It is not: a bulk createMutationQuery delete
        // goes straight to the database, so the rows are gone before the first insert is
        // enqueued and no flush is needed between them. This test is the evidence for that
        // claim - it stayed green when both flushes were removed - so it is also what would go
        // red if someone made the delete lazy. Creating a composition never exercises it; only
        // editing one does.
        long versionId = draftVersion();
        long first = questionWithVersions("שאלה א", 1);
        long second = questionWithVersions("שאלה ב", 1);

        inTx(session -> {
            repository.replaceComposition(session, versionId, List.of(
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, first), first, 50, 1),
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, second), second, 50, 2)));
            return null;
        });

        inTx(session -> {
            repository.replaceComposition(session, versionId, List.of(
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, second), second, 60, 1),
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, first), first, 40, 2)));
            return null;
        });

        List<PinnedQuestion> paper = inTx(session -> repository.findComposition(session, versionId));

        assertThat(paper).extracting(PinnedQuestion::text).containsExactly("שאלה ב", "שאלה א");
        assertThat(paper).extracting(PinnedQuestion::points).containsExactly(60, 40);
    }

    @Test
    @DisplayName("calling it twice in one transaction is refused, which is why §5.6 says once")
    void twoCompositionWritesInOneTransactionAreRefused() {
        // The measurement behind replaceComposition's javadoc. A bulk delete goes straight to the
        // database, which is why no flush is needed between the delete and the inserts - and is
        // equally why it does NOT evict anything from the persistence context. ExamVersionQuestion
        // has an assigned composite id, so the instances the first call persisted are still
        // managed under those keys and the second call's re-pin collides inside Hibernate before
        // any SQL is attempted.
        //
        // Pinned as a test rather than asserted in prose because the javadoc's neighbouring claim
        // says "measured rather than assumed", and two claims formatted alike had better both be
        // measured. Contract §5.6 makes each write one transaction, so no supported path does
        // this; a compose-then-adjust path would need session.clear() or a second transaction.
        long versionId = draftVersion();
        long first = questionWithVersions("שאלה א", 1);
        long second = questionWithVersions("שאלה ב", 1);

        assertThatThrownBy(() -> runInTx(session -> {
            repository.replaceComposition(session, versionId, List.of(
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, first), first, 100, 1)));
            repository.replaceComposition(session, versionId, List.of(
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, first), first, 50, 1),
                    new ExamBuildRepository.Pin(latestVersionIdOf(session, second), second, 50, 2)));
        }))
                .isInstanceOf(EntityExistsException.class)
                .hasRootCauseInstanceOf(NonUniqueObjectException.class);
    }

